  comparison: { inputs: ['NeedGrades', 'Profile', 'strengthenGrade'],
    equipmentRows: equipment.length, catalogCases: cases.length - boundaries.length,
    boundaryCases: boundaries.length, mismatches: 0, samples: comparisons.slice(-boundaries.length) },
