const artifacts = { 'ForgeEnhancementCost.java': java, 'forge-cost.evidence.json': `${JSON.stringify(report, null, 2)}\n` };
for (const [name, content] of Object.entries(artifacts)) {
  const path = join(output, name);
  if (args[0] === '--write') writeFileSync(path, content);
  else if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) {
    throw new Error(`Recorded artifact differs: ${basename(path)}; review and run with --write`);
  }
}
