import { asset as readAsset } from './assets.mjs';
// Third AutoForge adapter: the quest condition vocabulary.
//
// t_s_questcondiction drives conditions from data (CondictionType + Para1..4),
// but the meaning of each CondictionType lives only in the client. This adapter
// anchors the client's enum, cross-references it against the shipped catalogue
// and emits the Java side of the vocabulary. It deliberately does NOT guess the
// semantics of any type it cannot anchor: unknown ids are reported as a gap so
// the engine can refuse them instead of inventing behaviour.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.env.AUTOFORGE_CLIENT_ROOT; if (!root) throw new Error('AUTOFORGE_CLIENT_ROOT required');
const output = process.env.AUTOFORGE_OUTPUT_DIR; if (!output) throw new Error('AUTOFORGE_OUTPUT_DIR required');
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--write')) {
  throw new Error('Usage: node tools/autoforge-v2/quest-conditions.mjs [--write]');
}

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
function asset(path) { return readAsset(root,path); }
function anchor(source, pattern) {
  const matches = [...source.text.matchAll(pattern)];
  if (matches.length !== 1) throw new Error(`Expected one match for ${pattern}, got ${matches.length}`);
  const match = matches[0];
  const start = Buffer.byteLength(source.text.slice(0, match.index));
  const end = start + Buffer.byteLength(match[0]);
  return { match, evidence: { start, end, sha256: sha256(Buffer.from(match[0], 'utf8')) } };
}

const bundle = asset('js/bundle_release-ad60bfe795.js');
const conditions = asset('res/release/config/t_s_questcondiction-257a97b1b1.json');
const quests = asset('res/release/config/t_s_questtemplate-f38c33000a.json');

// 1. The vocabulary itself: one assignment per constant, anchored as a span.
const enumAnchor = anchor(bundle, /class hc\{\}((?:hc\.[A-Z_][A-Z_0-9]*=\d+,?)+);/g);
const names = new Map();
for (const [, name, value] of enumAnchor.match[1].matchAll(/(?:^|,)?hc\.([A-Z_][A-Z_0-9]*)=(\d+)/g)) {
  const id = Number(value);
  if (names.has(id)) throw new Error(`Duplicate condition id ${id}`);
  if (!Number.isInteger(id) || id < 1) throw new Error(`Invalid condition id for ${name}: ${value}`);
  names.set(id, name);
}
if (names.size < 2) throw new Error('Condition enum did not parse');

// A Java identifier must survive the round trip; refuse rather than mangle.
for (const [id, name] of names) {
  if (!/^[A-Z][A-Z0-9_]*$/.test(name)) throw new Error(`Unsafe enum constant ${id}: ${name}`);
}

// 2. Every site that dispatches on CondictionType, recorded so the per-type
//    handler can be extracted next with a known target instead of a search.
const dispatchers = [...bundle.text.matchAll(/switch\(\w+\.CondictionType\)/g)].map(match => {
  const start = Buffer.byteLength(bundle.text.slice(0, match.index));
  return { start, end: start + Buffer.byteLength(match[0]), sha256: sha256(Buffer.from(match[0], 'utf8')) };
});
if (!dispatchers.length) throw new Error('No CondictionType dispatcher found');

// 3. Cross-reference against the shipped catalogue.
const conditionRows = JSON.parse(conditions.text.replace(/^﻿/, '')).t_s_questcondition
  ?? JSON.parse(conditions.text.replace(/^﻿/, '')).t_s_questcondiction;
const questRows = JSON.parse(quests.text.replace(/^﻿/, '')).t_s_questtemplate;
if (!Array.isArray(conditionRows) || !conditionRows.length) throw new Error('Empty condition catalogue');
if (!Array.isArray(questRows) || !questRows.length) throw new Error('Empty quest catalogue');

const usage = new Map();
for (const row of conditionRows) {
  const id = row.CondictionType;
  if (!Number.isInteger(id)) throw new Error(`Invalid CondictionType in row ${row.CondictionID}`);
  usage.set(id, (usage.get(id) ?? 0) + 1);
}
const used = [...usage.keys()].sort((a, b) => a - b);
const knownUsed = used.filter(id => names.has(id));
const unknownUsed = used.filter(id => !names.has(id));
const rowsWithKnownType = conditionRows.filter(row => names.has(row.CondictionType)).length;

// Conditions are grouped per quest by TemplateId; a quest may need several.
const perQuest = new Map();
for (const row of conditionRows) {
  perQuest.set(row.TemplateId, (perQuest.get(row.TemplateId) ?? 0) + 1);
}
const questsWithConditions = questRows.filter(row => perQuest.has(row.TemplateId)).length;
const maxConditions = Math.max(...perQuest.values());
const withPrerequisite = questRows.filter(row => (row.PreQuestId ?? 0) > 0).length;

const java = `// Generated by tools/autoforge-v2/quest-conditions.mjs from the client's
// condition enum (class hc) and t_s_questcondiction. Do not edit by hand:
// re-run the adapter instead.
import java.util.Optional;

/**
 * Quest condition types as the client names them, keyed by
 * {@code t_s_questcondiction.CondictionType}.
 *
 * <p>Only ids anchored in the client bundle are named here. The catalogue also
 * carries ids this enum does not know; {@link #of(int)} returns an empty
 * {@code Optional} for them, and callers must treat those as an explicit
 * unsupported condition rather than guessing an interpretation.</p>
 */
public enum QuestConditionType {
${[...names].sort((a, b) => a[0] - b[0]).map(([id, name]) => `    ${name}(${id})`).join(',\n')};

    private static final QuestConditionType[] BY_ID = values();

    private final int id;

    QuestConditionType(int id) {
        this.id = id;
    }

    /** The {@code CondictionType} value this constant was extracted from. */
    public int id() {
        return id;
    }

    /** Empty when the id is not named by the client the server ships against. */
    public static Optional<QuestConditionType> of(int id) {
        for (QuestConditionType type : BY_ID) {
            if (type.id == id) return Optional.of(type);
        }
        return Optional.empty();
    }
}
`;

const report = {
  rule: 'quest.condition.vocabulary',
  sources: [bundle, conditions, quests].map(({ path, sha256 }) => ({ path, sha256: sha256 })),
  spanConvention: 'UTF-8 byte offsets, inclusive start and exclusive end',
  client: {
    symbol: 'hc (condition type enum)',
    definition: enumAnchor.evidence,
    members: [...names].sort((a, b) => a[0] - b[0]).map(([id, name]) => ({ id, name })),
    dispatchers: dispatchers,
    dispatcherNote: 'Each site is a switch over CondictionType; extracting the '
      + 'per-type handler is the next adapter.',
  },
  catalogue: {
    conditionRows: conditionRows.length,
    questRows: questRows.length,
    questsWithConditions: questsWithConditions,
    questsWithPrerequisite: withPrerequisite,
    maxConditionsPerQuest: maxConditions,
    distinctTypesUsed: used.length,
    knownTypesUsed: knownUsed.length,
    unknownTypesUsed: unknownUsed,
    rowsWithKnownType: rowsWithKnownType,
    rowsWithUnknownType: conditionRows.length - rowsWithKnownType,
    usageById: Object.fromEntries(used.map(id => [id, usage.get(id)])),
  },
  generated: { path: 'generated/QuestConditionType.java', sha256: sha256(java) },
  gaps: [
    'The semantics of Para1..Para4 are per-type and are not extracted yet; only '
      + 'the type vocabulary is anchored here.',
    unknownUsed.length
      ? `${unknownUsed.length} CondictionType value(s) used by the catalogue have no `
        + 'name in the client enum and stay unsupported until their dispatcher case is found.'
      : 'Every catalogue type is named by the client enum.',
    'No condition is evaluated by this adapter: the engine that consumes the '
      + 'vocabulary is a separate change.',
  ],
};

const artifacts = {
  'QuestConditionType.java': java,
  'quest-conditions.evidence.json': `${JSON.stringify(report, null, 2)}\n`,
};
for (const [name, content] of Object.entries(artifacts)) {
  const path = join(output, name);
  if (args[0] === '--write') writeFileSync(path, content);
  else if (!existsSync(path) || readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) {
    throw new Error(`Recorded artifact differs or is missing: ${basename(path)}; review and run with --write`);
  }
}
console.log(`AutoForge: ${names.size} condition types anchored, ${unknownUsed.length} unknown in use`);
console.log(`  catalogue: ${conditionRows.length} conditions / ${questRows.length} quests, `
  + `${questsWithConditions} with conditions, max ${maxConditions} per quest`);
console.log(`  rows on a named type: ${rowsWithKnownType}/${conditionRows.length}`);
console.log(`  dispatchers: ${dispatchers.length}`);
if (unknownUsed.length) console.log(`  unknown ids in use: ${unknownUsed.join(', ')}`);
