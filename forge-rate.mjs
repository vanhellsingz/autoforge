import { asset as readAsset } from './assets.mjs';
// Second AutoForge adapter: the common-enhancement success rate and the two
// guards the client applies before it sends U_C_ITEM_STRENGTHEN.
//
// Client bytes are data. Every number emitted into Java is captured from the
// bundle by an anchored pattern, so a change in the client fails this program
// instead of silently producing stale code.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, rmdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.env.AUTOFORGE_CLIENT_ROOT; if (!root) throw new Error('AUTOFORGE_CLIENT_ROOT required');
const output = process.env.AUTOFORGE_OUTPUT_DIR; if (!output) throw new Error('AUTOFORGE_OUTPUT_DIR required');
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--write')) {
  throw new Error('Usage: node tools/autoforge-v2/forge-rate.mjs [--write]');
}

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
function asset(path) { return readAsset(root,path); }
function anchor(source, pattern) {
  const matches = [...source.text.matchAll(pattern)];
  if (matches.length !== 1) throw new Error(`Expected one match for ${pattern}, got ${matches.length}`);
  const match = matches[0];
  const start = Buffer.byteLength(source.text.slice(0, match.index));
  const end = start + Buffer.byteLength(match[0]);
  return { match, evidence: { start, end, sha256: sha256(Buffer.from(match[0], 'utf8')) } };
}

const bundle = asset('js/bundle_release-ad60bfe795.js');

// 1. The two tuning constants, read as integers straight from the statics.
const successRate = anchor(bundle, /cJ\.SUCCESS_RATE=(\d+)/g);
const rateStep = anchor(bundle, /cJ\.RATE_STEP=(\d+)/g);
const constants = {
  base: Number(successRate.match[1]),
  step: Number(rateStep.match[1]),
};

// 2. getSuccessRate(t, e): t is the equipment, e is the optional second slot
//    whose templateInfo.Property1 is added to the rate. The clamp bounds are
//    captured as groups so they stay client-owned values.
const rule = anchor(bundle,
  /static getSuccessRate\(t,e\)\{let i;return t&&\(i=cJ\.SUCCESS_RATE-t\.strengthenGrade\*cJ\.RATE_STEP,i=i>(\d+)\?(\d+):i<(\d+)\?(\d+):i\),e&&\(i\+=e\.templateInfo\.Property(\d+)\),i=i>(\d+)\?(\d+):i,i\}/g);
const [, upperBound, upperValue, lowerBound, lowerValue, propertyField, finalBound, finalValue] = rule.match;
const clamps = {
  min: Number(lowerValue),
  max: Number(upperValue),
  finalMax: Number(finalValue),
  property: `Property${propertyField}`,
};
if (Number(upperBound) !== clamps.max || Number(lowerBound) !== clamps.min) {
  throw new Error(`Unexpected clamp test bounds: ${upperBound}/${lowerBound}`);
}
if (Number(finalBound) !== clamps.finalMax) {
  throw new Error(`Unexpected final clamp bound: ${finalBound}`);
}
if (!Number.isInteger(constants.base) || !Number.isInteger(constants.step)
    || !Number.isInteger(clamps.min) || !Number.isInteger(clamps.max)
    || !Number.isInteger(clamps.finalMax)) {
  throw new Error('Non-integer client constants');
}

// 3. checkCanIntensify(cost, equip): gold first, then the level ceiling. The
//    messages are recorded so the server can map them to the same conditions.
const guard = anchor(bundle, /static checkCanIntensify\(t,e\)\{let i=e\.strengthenGrade,s=qo\.Instance\.gold\.count,n="";return t>s\?\(n=B\.Instance\.GetTranslation\("store\.utils\.StoreHelper\.command01",t-s\),a6\.Instance\.show\(n\),!1\):!\(i>=e\.templateInfo\.StrengthenMax\)\|\|\(n=B\.Instance\.GetTranslation\("store\.utils\.StoreHelper\.command02"\),a6\.Instance\.show\(n\),!1\)\}/g);

// 4. The confirm flow: onBtnConfirm asks again whenever the rate is at or below
//    the risk threshold, then sends the same empty packet. The threshold is a
//    client-only prompt, but it is part of the rule's observable behaviour.
const confirm = anchor(bundle, /onBtnConfirm\(\)\{let t=this\.equip1\.info;if\(t\)if\(cJ\.getSuccessRate\(t,this\.equip2\.info\)<=(\d+)\)\{/g);
const riskThreshold = Number(confirm.match[1]);

// 5. strengthen(): the client re-checks gold against the *displayed* cost and
//    only then sends the opcode. The packet still carries no body.
const strengthen = anchor(bundle, /strengthen\(\)\{if\(qo\.Instance\.gold\.count<Number\(ga\.trim\(this\.txtCost\.text\)\)\)\{let t=B\.Instance\.GetTranslation\("public\.gold"\);a6\.Instance\.show\(t\)\}else this\.btnComp\.enabled=!1,this\.ctrl\.data\.isIntensifing=!0,this\.ctrl\.sendItemIntensify\(\)\}/g);

const java = `// Generated by tools/autoforge-v2/forge-rate.mjs from getSuccessRate and
// checkCanIntensify. Do not edit by hand: re-run the adapter instead.
public final class ForgeEnhancementRules {
    private ForgeEnhancementRules() {}

    /** cJ.SUCCESS_RATE - the rate before the grade penalty. */
    public static final int SUCCESS_RATE = ${constants.base};
    /** cJ.RATE_STEP - rate points lost per strengthen grade. */
    public static final int RATE_STEP = ${constants.step};
    /** Lower clamp applied before the bonus slot is added. */
    public static final int MIN_RATE = ${clamps.min};
    /** Upper clamp applied before the bonus slot is added. */
    public static final int MAX_RATE = ${clamps.max};
    /** Upper clamp applied after the bonus slot is added. */
    public static final int FINAL_MAX_RATE = ${clamps.finalMax};
    /** getSuccessRate asks for confirmation at or below this rate. */
    public static final int RISK_CONFIRM_THRESHOLD = ${riskThreshold};

    /**
     * Common enhancement success rate in whole percent.
     *
     * @param strengthenGrade current enchantment level of the equipment
     * @param property1       templateInfo.${clamps.property} of the second forge
     *                        slot; the client adds it to the rate. The C2S packet
     *                        carries no slot selection, so callers must resolve the second slot from authoritative state.
     */
    public static int successRate(int strengthenGrade, int property1) {
        int rate = SUCCESS_RATE - strengthenGrade * RATE_STEP;
        rate = Math.min(Math.max(rate, MIN_RATE), MAX_RATE);
        rate += property1;
        return Math.min(rate, FINAL_MAX_RATE);
    }

    /** checkCanIntensify: enough gold first, then below the level ceiling. */
    public static boolean canIntensify(long cost, long gold, int strengthenGrade, int strengthenMax) {
        return cost <= gold && strengthenGrade < strengthenMax;
    }

    /** True when the client would prompt for confirmation before enhancing. */
    public static boolean needsRiskConfirm(int rate) {
        return rate <= RISK_CONFIRM_THRESHOLD;
    }
}
`;

// Reviewed transcription of the client method. Independent of the emitter.
function clientRate(grade, property1, withBonus) {
  let i;
  if (withBonus) {
    i = constants.base - grade * constants.step;
    i = i > clamps.max ? clamps.max : i < clamps.min ? clamps.min : i;
    i += property1;
    i = i > clamps.finalMax ? clamps.finalMax : i;
  } else {
    i = constants.base - grade * constants.step;
    i = i > clamps.max ? clamps.max : i < clamps.min ? clamps.min : i;
  }
  return i;
}
function clientCanIntensify(cost, gold, grade, max) {
  return !(cost > gold) && !(grade >= max);
}

const grades = [];
for (let grade = 0; grade <= 120; grade++) grades.push(grade);
const bonuses = [-1000, -100, -11, -10, -1, 0, 1, 5, 10, 20, 50, 99, 100, 101, 500];
const cases = [];
for (const grade of grades) {
  for (const bonused of [true, false]) {
    for (const bonus of (bonused ? bonuses : [0])) cases.push([grade, bonused ? bonus : 0, bonused]);
  }
}
const guardCases = [];
for (const [cost, gold, grade, max] of [[0, 0, 0, 1], [1, 0, 0, 1], [0, 0, 1, 1], [500, 499, 0, 10],
  [500, 500, 0, 10], [537, 1000, 5, 6], [537, 1000, 6, 6], [1, 1, 0, 1], [200, 199, 9, 10]]) {
  guardCases.push([cost, gold, grade, max]);
}

function runJava(source) {
  const temp = mkdtempSync(join(tmpdir(), 'wartune-forge-rate-'));
  try {
    const file = join(temp, 'ForgeEnhancementRules.java');
    const runner = join(temp, 'Compare.java');
    writeFileSync(file, source);
    writeFileSync(runner, `import java.io.BufferedReader;
import java.io.InputStreamReader;

class Compare {
    public static void main(String[] args) throws Exception {
        var reader = new BufferedReader(new InputStreamReader(System.in));
        for (String line; (line = reader.readLine()) != null;) {
            String[] f = line.split(" ");
            if (f[0].equals("rate")) {
                System.out.println(ForgeEnhancementRules.successRate(
                    Integer.parseInt(f[1]), Integer.parseInt(f[2])));
            } else if (f[0].equals("guard")) {
                System.out.println(ForgeEnhancementRules.canIntensify(
                    Long.parseLong(f[1]), Long.parseLong(f[2]),
                    Integer.parseInt(f[3]), Integer.parseInt(f[4])) ? 1 : 0);
            } else {
                // needsRiskConfirm takes a rate, not a grade: the client asks
                // for confirmation from the rate it computed, so drive it the
                // same way here.
                System.out.println(ForgeEnhancementRules.needsRiskConfirm(
                    ForgeEnhancementRules.successRate(Integer.parseInt(f[1]), 0)) ? 1 : 0);
            }
        }
    }
}
`);
    execFileSync('javac', ['--release', '21', '-d', temp, file, runner]);
    return execFileSync('java', ['-cp', temp, 'Compare'], {
      encoding: 'utf8',
      input: [
        ...cases.map(([grade, bonus, bonused]) => `rate ${grade} ${bonused ? bonus : 0}`),
        ...guardCases.map(([cost, gold, grade, max]) => `guard ${cost} ${gold} ${grade} ${max}`),
        ...Array.from({ length: 121 }, (_, grade) => `risk ${grade}`),
      ].join('\n') + '\n',
      maxBuffer: 8 * 1024 * 1024,
    }).trim().split(/\r?\n/);
  } finally {
    for (const name of readdirSync(temp)) rmSync(join(temp, name));
    rmdirSync(temp);
  }
}

function hasJavac() {
  try {
    execFileSync('javac', ['-version'], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

// The published samples must not depend on whether a JDK is available: the
// recorded artifact has to be byte-identical on a laptop without javac and in
// CI, otherwise the drift check fires for an environment reason rather than a
// rule change.
const SAMPLE_INPUTS = [[0, 0], [1, 0], [5, 0], [9, 0], [10, 0], [11, 0], [50, 0],
  [0, 10], [11, 20], [11, -50]];
const samples = SAMPLE_INPUTS.map(([grade, bonus]) => ({
  grade: grade, property1: bonus, rate: clientRate(grade, bonus, true),
}));

const expected = [
  ...cases.map(([grade, bonus, bonused]) => String(clientRate(grade, bonus, bonused))),
  ...guardCases.map(([cost, gold, grade, max]) => (clientCanIntensify(cost, gold, grade, max) ? '1' : '0')),
  ...Array.from({ length: 121 }, (_, grade) =>
    (clientRate(grade, 0, false) <= riskThreshold ? '1' : '0')),
];

let mismatches = 0;
let javaParity = 'skipped: no javac on PATH';

if (!hasJavac()) {
  throw new Error('AUTOFORGE_REQUIRE_JAVA=1 but javac is not on PATH');
}

if (hasJavac()) {
  const actual = runJava(java);
  if (actual.length !== expected.length) {
    throw new Error(`Java returned ${actual.length} rows for ${expected.length} cases`);
  }
  const rows = [];
  expected.forEach((want, index) => {
    if (actual[index] !== want) {
      mismatches++;
      rows.push({ index, js: want, java: actual[index] });
    }
  });
  if (mismatches) throw new Error(`Java/JS divergence: ${JSON.stringify(rows.slice(0, 5))}`);
  javaParity = 'passed';
} else {
  // Without a JDK the emitted Java cannot be executed here. The rule is still
  // checked against the transcription, and the constants stay anchored to the
  // bundle bytes. CI runs the Java half on a hosted runner with JDK 21.
}

